#!/usr/bin/env node
/**
 * Write the database schema reference pages under `docs/database/` from the
 * JSON the control plane prints.
 *
 * Usage (from this repo, with the control plane checked out beside it):
 *
 *   (cd ../turbopanel && node scripts/schema-docs.mjs --json) > schema.json
 *   pnpm schema:sync schema.json          write docs/database/*.mdx + meta.json
 *   pnpm schema:sync --check schema.json  change nothing; exit 1 when the
 *                                         committed pages differ
 *
 * With no file argument the JSON is read from standard input. The pages are
 * committed, so the docs build never needs the control plane repo. Do not edit
 * them by hand: change the descriptions in the control plane and run this again.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const OUT_DIR = path.join(ROOT, 'docs', 'database')

const SMALL_WORDS = new Set(['a', 'and', 'in', 'of', 'or', 'the', 'to'])

/** Book title case for a group title taken from the control plane. */
export function titleCase(text) {
  return text
    .split(' ')
    .map((word, index) =>
      index > 0 && SMALL_WORDS.has(word) ? word : word.charAt(0).toUpperCase() + word.slice(1)
    )
    .join(' ')
}

/** Reject JSON that is not the control plane's list of groups. */
export function parseGroups(text) {
  const groups = JSON.parse(text)
  const valid =
    Array.isArray(groups) &&
    groups.length > 0 &&
    groups.every(
      (group) =>
        /^[a-z][a-z0-9-]*$/.test(group?.key) &&
        typeof group.title === 'string' &&
        typeof group.blurb === 'string' &&
        Array.isArray(group.tables) &&
        group.tables.every(
          (table) =>
            typeof table?.name === 'string' &&
            typeof table.summary === 'string' &&
            Array.isArray(table.columns) &&
            table.columns.every(
              (column) =>
                typeof column?.name === 'string' &&
                typeof column.type === 'string' &&
                typeof column.notNull === 'boolean' &&
                typeof column.text === 'string'
            )
        )
    )
  if (!valid) throw new TypeError('input is not the schema-docs JSON')
  return groups
}

/** Make prose safe for MDX and a table cell; code spans are left alone. */
export function mdxText(text) {
  return text
    .replace(/\s+/g, ' ')
    .split(/(`[^`]*`)/)
    .map((part, index) => (index % 2 === 1 ? part : part.replace(/[{}<>]/g, (char) => `\\${char}`)))
    .join('')
    .replaceAll('|', String.raw`\|`)
}

const FRONT_NOTE =
  '{/* Generated by scripts/sync-schema-docs.mjs from the control plane schema export. Do not edit by hand. */}'

const countColumns = (tables) => tables.reduce((sum, table) => sum + table.columns.length, 0)

const plural = (count, one) => `${count} ${one}${count === 1 ? '' : 's'}`

export function renderGroupPage(group) {
  const title = titleCase(group.title)
  const columns = countColumns(group.tables)
  const lines = [
    '---',
    `title: ${JSON.stringify(title)}`,
    `description: ${JSON.stringify(`${plural(group.tables.length, 'table')} and ${plural(columns, 'column')} in the ${title} group of the control plane database`)}`,
    '---',
    '',
    FRONT_NOTE,
    '',
    `# ${title}`,
    '',
    mdxText(group.blurb),
    '',
    'Tables in this group: ' +
      group.tables.map((table) => `[\`${table.name}\`](#${table.name})`).join(', ') +
      '.',
    '',
  ]
  for (const table of group.tables) {
    lines.push(`## \`${table.name}\` [#${table.name}]`, '')
    if (table.summary) lines.push(mdxText(table.summary), '')
    lines.push('| Column | Type | Required | Description |', '| --- | --- | --- | --- |')
    for (const column of table.columns) {
      lines.push(
        `| \`${column.name}\` | \`${column.type}\` | ${column.notNull ? 'yes' : 'no'} | ${mdxText(column.text)} |`
      )
    }
    lines.push('')
  }
  return lines.join('\n')
}

export function renderIndex(groups) {
  const tables = groups.reduce((sum, group) => sum + group.tables.length, 0)
  const columns = groups.reduce((sum, group) => sum + countColumns(group.tables), 0)
  const lines = [
    '---',
    'title: "Database"',
    'description: "Every table and column of the control plane database, grouped by what the data is for"',
    '---',
    '',
    FRONT_NOTE,
    '',
    '# Database',
    '',
    `The control plane keeps its state in one PostgreSQL database (PostgreSQL 18 or newer). This reference documents ${plural(tables, 'table')} and ${plural(columns, 'column')}, in ${plural(groups.length, 'group')}. Each group has its own page, with one section per table and a column table under it.`,
    '',
    '## How to Read the Pages',
    '',
    '- **Column** and **Type** are the column name and PostgreSQL type as the newest migration declares them.',
    '- **Required** says **yes** when the column is declared `NOT NULL`. A required column can still have a default.',
    '- **Description** says what the column holds. The standard columns (`id`, `created_at`, `updated_at`) and plain links to a parent row share one wording everywhere.',
    '',
    '## Groups',
    '',
    '| Group | Tables | Columns | What it holds |',
    '| --- | --- | --- | --- |',
    ...groups.map(
      (group) =>
        `| [${titleCase(group.title)}](/docs/database/${group.key}) | ${group.tables.length} | ${countColumns(group.tables)} | ${mdxText(group.blurb)} |`
    ),
    '',
    '## Where the Descriptions Come From',
    '',
    'The database itself carries no `COMMENT ON` descriptions. These pages are generated from the control plane source: the wording lives in its schema descriptions file, and the structure comes from the snapshot behind the newest migration. The pages are committed to the website and are not edited by hand.',
    '',
  ]
  return lines.join('\n')
}

export function renderMeta(groups) {
  return `${JSON.stringify({ title: 'Database', pages: ['index', ...groups.map((group) => group.key)] }, null, 2)}\n`
}

/** Every generated file as `{ name: content }`. */
export function renderAll(groups) {
  const files = { 'index.mdx': renderIndex(groups), 'meta.json': renderMeta(groups) }
  for (const group of groups) files[`${group.key}.mdx`] = renderGroupPage(group)
  return files
}

const generatedNames = (dir) =>
  existsSync(dir)
    ? readdirSync(dir).filter((name) => name.endsWith('.mdx') || name === 'meta.json')
    : []

/** Files that differ from `files`: written, missing, or stale. */
export function diffDir(dir, files) {
  const problems = []
  for (const [name, content] of Object.entries(files)) {
    const file = path.join(dir, name)
    if (!existsSync(file) || readFileSync(file, 'utf8') !== content) {
      problems.push(name)
    }
  }
  for (const name of generatedNames(dir)) {
    if (!(name in files)) problems.push(name)
  }
  return problems
}

export function writeDir(dir, files) {
  mkdirSync(dir, { recursive: true })
  for (const name of generatedNames(dir)) {
    if (!(name in files)) rmSync(path.join(dir, name))
  }
  for (const [name, content] of Object.entries(files)) {
    writeFileSync(path.join(dir, name), content)
  }
}

export function main(argv, { dir, readStdin, log, error }) {
  const check = argv.includes('--check')
  const file = argv.find((arg) => !arg.startsWith('--'))
  let groups
  try {
    groups = parseGroups(file ? readFileSync(file, 'utf8') : readStdin())
  } catch (cause) {
    error(`schema-sync: ${cause.message}`)
    return 1
  }
  const files = renderAll(groups)
  if (check) {
    const problems = diffDir(dir, files)
    if (problems.length === 0) {
      log('schema-sync: docs/database is up to date')
      return 0
    }
    error(`schema-sync: out of date: ${problems.join(', ')}`)
    return 1
  }
  writeDir(dir, files)
  log(`schema-sync: wrote ${Object.keys(files).length} files to docs/database`)
  return 0
}

/* v8 ignore start -- process entry point */
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exit(
    main(process.argv.slice(2), {
      dir: OUT_DIR,
      readStdin: () => readFileSync(0, 'utf8'),
      log: console.log,
      error: console.error,
    })
  )
}
/* v8 ignore stop */
